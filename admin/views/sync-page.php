			<div class="notice notice-info inline"><p><?php esc_html_e('There is nothing to sync for this template.', 'bulk-page-duplicator'); ?></p></div>
		<?php else : ?>
			<?php if (!$bulk_page_duplicator_sync->revisions_supported($bulk_page_duplicator_template)) : ?>
				<div class="notice notice-warning inline"><p><?php esc_html_e('Revisions are disabled for this content type, so a sync cannot be undone from the Revisions screen. Consider taking a backup first.', 'bulk-page-duplicator'); ?></p></div>
