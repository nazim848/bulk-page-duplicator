						<div class="bpd-dry-run-list-wrapper">
							<table class="bpd-dry-run-table widefat bpd-sync-table">
								<thead>
									<tr>
										<th scope="col"><?php esc_html_e('Item', 'bulk-page-duplicator'); ?></th>
										<th scope="col"><?php esc_html_e('State', 'bulk-page-duplicator'); ?></th>
										<th scope="col"><?php esc_html_e('Changes', 'bulk-page-duplicator'); ?></th>
										<th scope="col"><?php esc_html_e('Overwrite', 'bulk-page-duplicator'); ?></th>
									</tr>
								</thead>
								<tbody id="bpd-sync-table-body"></tbody>
							</table>
						</div>
					</div>

					<div class="bulk-page-dup-log-container" id="bpd-sync-log-container" style="display: none;">
						<h3><?php esc_html_e('Results Log', 'bulk-page-duplicator'); ?></h3>
						<div class="results-summary" id="bpd-sync-results-summary">
							<span class="summary-item summary-success"><span id="bpd-sync-result-updated">0</span> <?php esc_html_e('updated', 'bulk-page-duplicator'); ?></span>
							<span class="summary-item summary-skipped"><span id="bpd-sync-result-skipped">0</span> <?php esc_html_e('skipped', 'bulk-page-duplicator'); ?></span>
							<span class="summary-item summary-skipped"><span id="bpd-sync-result-unchanged">0</span> <?php esc_html_e('up to date', 'bulk-page-duplicator'); ?></span>
							<span class="summary-item summary-error"><span id="bpd-sync-result-error">0</span> <?php esc_html_e('errors', 'bulk-page-duplicator'); ?></span>
