						<div class="bulk-page-dup-log" id="bpd-sync-log"></div>
					</div>

					<div class="bulk-page-dup-history-container">
						<h3><?php esc_html_e('Recent Syncs', 'bulk-page-duplicator'); ?></h3>
						<div id="bpd-sync-history"></div>
						<p id="bpd-sync-history-empty" style="display: none; color: #666;"><?php esc_html_e('This template has not been synced yet.', 'bulk-page-duplicator'); ?></p>
					</div>
				</div>
			</div>
		<?php endif; ?>
	<?php endif; ?>
</div>
