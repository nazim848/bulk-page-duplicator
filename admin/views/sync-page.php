						<?php
						$bulk_page_duplicator_post_type_obj = get_post_type_object($bulk_page_duplicator_entry['post']->post_type);
						$bulk_page_duplicator_entry_title = '' !== $bulk_page_duplicator_entry['post']->post_title ? $bulk_page_duplicator_entry['post']->post_title : __('(no title)', 'bulk-page-duplicator');
