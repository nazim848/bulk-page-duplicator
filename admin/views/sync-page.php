<?php

/**
 * Template Sync screen
 *
 * @package BulkPageDuplicator
 *
 * @var Bulk_Page_Duplicator_Sync     $bulk_page_duplicator_sync
 * @var WP_Post|WP_Error|null         $bulk_page_duplicator_template
 */
if (!defined('ABSPATH')) exit;

$bulk_page_duplicator_main_url = admin_url('tools.php?page=bulk-page-duplicator');
?>
<div class="wrap bpd-sync-wrap">
	<h1 class="wp-heading-inline"><?php esc_html_e('Template Sync', 'bulk-page-duplicator'); ?></h1>
	<a href="<?php echo esc_url($bulk_page_duplicator_main_url); ?>" class="page-title-action"><?php esc_html_e('Back to Bulk Page Duplicator', 'bulk-page-duplicator'); ?></a>
	<hr class="wp-header-end">

	<?php if (is_wp_error($bulk_page_duplicator_template)) : ?>
		<div class="notice notice-error"><p><?php echo esc_html($bulk_page_duplicator_template->get_error_message()); ?></p></div>
		<p><a href="<?php echo esc_url(Bulk_Page_Duplicator_Sync_Admin::get_page_url()); ?>"><?php esc_html_e('Choose another template', 'bulk-page-duplicator'); ?></a></p>

