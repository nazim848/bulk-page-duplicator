			if ($bulk_page_duplicator_row_template && 'trash' !== $bulk_page_duplicator_row_template->post_status && current_user_can('edit_post', $bulk_page_duplicator_row_template->ID)) {
				$bulk_page_duplicator_templates[] = array(
					'post'  => $bulk_page_duplicator_row_template,
					'count' => $bulk_page_duplicator_row['count'],
				);
			}
		}
		?>
		<p><?php esc_html_e('Push changes you made to a template to the items generated from it. Choose a template:', 'bulk-page-duplicator'); ?></p>
		<?php if (empty($bulk_page_duplicator_templates)) : ?>
			<p><?php esc_html_e('No templates with generated items were found. Only items generated by recent versions of Bulk Page Duplicator remember their template.', 'bulk-page-duplicator'); ?></p>
