					<div id="bpd-sync-preview-panel" style="display: none;">
						<h2><?php esc_html_e('Preview', 'bulk-page-duplicator'); ?></h2>
						<div class="bpd-dry-run-summary">
							<div class="bpd-summary-item bpd-summary-create">
								<span class="bpd-summary-count" id="bpd-sync-count-change">0</span>
								<span class="bpd-summary-label"><?php esc_html_e('Will update', 'bulk-page-duplicator'); ?></span>
							</div>
							<div class="bpd-summary-item bpd-summary-total">
								<span class="bpd-summary-count" id="bpd-sync-count-same">0</span>
								<span class="bpd-summary-label"><?php esc_html_e('Up to date', 'bulk-page-duplicator'); ?></span>
							</div>
							<div class="bpd-summary-item bpd-summary-skip">
								<span class="bpd-summary-count" id="bpd-sync-count-edited">0</span>
								<span class="bpd-summary-label"><?php esc_html_e('Edited by hand', 'bulk-page-duplicator'); ?></span>
							</div>
							<div class="bpd-summary-item bpd-summary-error">
								<span class="bpd-summary-count" id="bpd-sync-count-error">0</span>
								<span class="bpd-summary-label"><?php esc_html_e('Cannot sync', 'bulk-page-duplicator'); ?></span>
							</div>
						</div>
						<p>
							<label>
								<input type="checkbox" id="bpd-sync-include-edited">
								<?php esc_html_e('Also overwrite all items edited by hand', 'bulk-page-duplicator'); ?>
							</label>
						</p>
						<p class="description"><?php esc_html_e('Items edited by hand since they were generated (or last synced) are skipped unless you tick "Overwrite" for them. "Possibly edited" means the item was generated before edit tracking existed and has been modified since.', 'bulk-page-duplicator'); ?></p>
						<div class="log-filters bpd-sync-filters">
							<button type="button" class="button button-small bpd-sync-filter active" data-filter="all"><?php esc_html_e('All', 'bulk-page-duplicator'); ?></button>
							<button type="button" class="button button-small bpd-sync-filter" data-filter="change"><?php esc_html_e('Will update', 'bulk-page-duplicator'); ?></button>
							<button type="button" class="button button-small bpd-sync-filter" data-filter="edited"><?php esc_html_e('Edited by hand', 'bulk-page-duplicator'); ?></button>
							<button type="button" class="button button-small bpd-sync-filter" data-filter="error"><?php esc_html_e('Cannot sync', 'bulk-page-duplicator'); ?></button>
