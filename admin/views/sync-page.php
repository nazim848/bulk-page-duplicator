								<?php echo esc_html($bulk_page_duplicator_labels[$bulk_page_duplicator_field]); ?>
							</label>
							<p class="description"><?php echo esc_html($bulk_page_duplicator_descriptions[$bulk_page_duplicator_field]); ?></p>
						<?php endforeach; ?>
					</fieldset>

					<div class="bulk-page-dup-progress-container" id="bpd-sync-progress" style="display: none;">
						<h3><?php esc_html_e('Progress', 'bulk-page-duplicator'); ?></h3>
						<div class="bulk-page-dup-progress-bar">
							<div class="bulk-page-dup-progress-bar-inner"></div>
						</div>
						<p class="bulk-page-dup-progress-text">0%</p>
						<p class="bulk-page-dup-status-text"></p>
					</div>

					<p class="submit">
						<button type="button" id="bpd-sync-preview" class="button button-secondary button-large"><?php esc_html_e('Preview changes', 'bulk-page-duplicator'); ?></button>
